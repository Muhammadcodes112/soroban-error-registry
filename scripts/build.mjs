#!/usr/bin/env node
// Bundles registry/ into the files tools consume:
//   dist/registry.json  plain JSON, for any language
//   dist/registry.mjs   the same data as an ES module, so the JS library works in
//                       browsers, bundlers, Deno and Node without filesystem access
import { mkdir, writeFile } from "node:fs/promises";
import { join } from "node:path";
import { ROOT, loadRegistry, keyOf, hostKey } from "./lib/load.mjs";

const files = await loadRegistry();
const contracts = {};
const host = {};
const byContractId = {};
const byWasmHash = {};

for (const { path, data } of files) {
  if (data.kind === "host") {
    for (const e of data.errors) host[hostKey(e)] = { ...e, source: data.source, network_protocol: data.protocol.network_protocol };
    continue;
  }
  const key = keyOf(path);
  contracts[key] = {
    protocol: data.protocol,
    contract: data.contract,
    source: data.source,
    errors: Object.fromEntries(data.errors.map((e) => [e.code, e])),
  };
  for (const d of data.deployments ?? []) {
    if (d.contract_id) byContractId[d.contract_id] = key;
    if (d.wasm_hash) byWasmHash[d.wasm_hash] = key;
  }
}

// Deterministic output (no timestamp) so CI can check that dist/ is up to date.
const bundle = { schema_version: 1, contracts, host, byContractId, byWasmHash };
const json = JSON.stringify(bundle, null, 2);
await mkdir(join(ROOT, "dist"), { recursive: true });
await writeFile(join(ROOT, "dist/registry.json"), json + "\n");
await writeFile(join(ROOT, "dist/registry.mjs"), `// Generated by scripts/build.mjs — do not edit.\nexport default ${json};\n`);
console.log(`✓ dist/ — ${Object.keys(contracts).length} contracts, ${Object.keys(host).length} host errors`);
